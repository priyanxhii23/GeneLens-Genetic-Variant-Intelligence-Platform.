/** Global data-display mode: REAL, SYNTHETIC or BOTH. Persisted across reloads. */
import { createContext, useContext, useEffect, useState, type ReactNode } from "react";
import type { ProvMode } from "./types";

const KEY = "genelens-provenance";
const Ctx = createContext<{ mode: ProvMode; setMode: (m: ProvMode) => void }>({ mode: "REAL", setMode: () => {} });

export function ProvenanceProvider({ children }: { children: ReactNode }) {
  const [mode, setMode] = useState<ProvMode>(() => {
    try { const v = localStorage.getItem(KEY); return v === "SYNTHETIC" || v === "BOTH" ? v : "REAL"; } catch { return "REAL"; }
  });
  useEffect(() => { try { localStorage.setItem(KEY, mode); } catch { /* storage blocked */ } }, [mode]);
  return <Ctx.Provider value={{ mode, setMode }}>{children}</Ctx.Provider>;
}
export const useProvenance = () => useContext(Ctx);
export const PROV_META = {
  REAL: { label: "Real", color: "gold", hint: "Only genuine records downloaded from public databases" },
  SYNTHETIC: { label: "Synthetic", color: "pink", hint: "Only records generated by the Synthetic Lab" },
  BOTH: { label: "Both", color: "accent", hint: "Real and synthetic side by side, outlined gold and pink – never pooled" },
} as const;
