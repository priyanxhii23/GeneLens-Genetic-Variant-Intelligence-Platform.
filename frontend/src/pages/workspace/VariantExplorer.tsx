import { AnimatePresence, motion } from "framer-motion";
import { ArrowDown, ArrowUp, ChevronLeft, ChevronRight, Download, ExternalLink, Search, X } from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import Plot from "../../components/Plot";
import { ClassBadge, ErrorState, Guide, GuideItem, HelixLoader, Insight, MatchBadge, NeedsAnalysis, PageHeader, Panel, PriorityBadge, ProvenanceBadge, Stars, stagger, Term } from "../../components/ui";
import { useProvenance } from "../../lib/provenance";
import { api } from "../../lib/api";
import { useAnalysis, useFetch } from "../../lib/analysis";
import { CLASS_META, fmtAF, fmtInt, MATCH_LABELS, POP_LABELS, token } from "../../lib/format";
import type { Annotation, CoarseClass, VariantDetail } from "../../lib/types";

const CLASSES: CoarseClass[] = ["P_LP", "VUS", "B_LB", "CONFLICTING", "OTHER", "NOT_IN_CLINVAR"];

export function VariantDrawer({ id, onClose }: { id: number | null; onClose: () => void }) {
  const [v, setV] = useState<VariantDetail | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [ann, setAnn] = useState<Annotation | null>(null);
  const [annBusy, setAnnBusy] = useState(false);
  const [annErr, setAnnErr] = useState<string | null>(null);
  useEffect(() => {
    setV(null); setErr(null); setAnn(null); setAnnErr(null);
    if (id !== null) api.variant(id).then(setV).catch((e) => setErr(e.message));
  }, [id]);
  const annotate = () => {
    if (id === null) return;
    setAnnBusy(true); setAnnErr(null);
    api.annotation(id).then(setAnn).catch((e) => setAnnErr(e.message)).finally(() => setAnnBusy(false));
  };
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);
  const pops = (v?.populations ?? []).filter((p) => p.an > 0);
  return (
    <AnimatePresence>
      {id !== null && (
        <>
          <motion.div className="fixed inset-0 z-40 bg-bg/60 backdrop-blur-sm" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={onClose} />
          <motion.aside role="dialog" aria-label="Variant detail" initial={{ x: "100%" }} animate={{ x: 0 }} exit={{ x: "100%" }} transition={{ type: "spring", damping: 30, stiffness: 260 }}
            className="fixed inset-y-0 right-0 z-50 w-full max-w-xl overflow-y-auto border-l border-line bg-surface p-6 scrollbar-thin">
            <button className="btn-ghost absolute right-4 top-4 !px-2" onClick={onClose} aria-label="Close"><X size={16} /></button>
            {err && <ErrorState message={err} />}
            {!v && !err && <HelixLoader label="Loading variant" />}
            {v && (
              <div className="space-y-5">
                <div>
                  <div className="eyebrow mb-1">variant inspection</div>
                  <h2 className={`break-all font-mono text-[17px] ${v.provenance === "SYNTHETIC" ? "syn-id inline-block" : ""}`}>{v.variant_key}</h2>
                  <div className="mt-2 flex flex-wrap gap-2"><ProvenanceBadge p={v.provenance} /><ClassBadge cls={v.coarse_class} label={v.clinical_significance} /><MatchBadge s={v.match_status} />
                    {v.variant_type && <span className="chip border-line text-muted">{v.variant_type}</span>}</div>
                  {v.provenance === "SYNTHETIC" && <p className="mt-2 text-[13px] text-pink">Simulated record generated by GeneLens – not an observation from any database.</p>}
                </div>
                <dl className="grid grid-cols-2 gap-x-4 gap-y-3 text-sm">
                  {([
                    ["HGVS (c.)", v.hgvsc ?? v.name], ["HGVS (p.)", v.hgvsp], ["rsID", v.rsid], ["Consequence", v.consequence?.replace(/_/g, " ")],
                    ["Allele count (AC)", fmtInt(v.ac)], ["Allele number (AN)", fmtInt(v.an)], ["Allele frequency", fmtAF(v.af)],
                    ["AF exome / genome", `${fmtAF(v.af_exome)} / ${fmtAF(v.af_genome)}`], ["grpmax AF", `${fmtAF(v.popmax_af)} ${v.popmax_population ? `(${v.popmax_population})` : ""}`],
                    ["Homozygotes", fmtInt(v.homozygote_count)], ["Clinical significance", v.clinical_significance], ["Review status", v.review_status],
                    ["ClinVar variation ID", v.clinvar_variation_id], ["Allele ID", v.clinvar_allele_id], ["Submissions", fmtInt(v.submitter_count)],
                    ["Last evaluated", v.last_evaluated], ["Match method", v.match_method], ["Match confidence", v.match_confidence?.toString()],
                  ] as [string, string | null | undefined][]).map(([k, val]) => (
                    <div key={k}><dt className="eyebrow">{k}</dt><dd className="mt-0.5 break-words">{val || "—"}</dd></div>
                  ))}
                  <div><dt className="eyebrow">Review stars</dt><dd className="mt-1"><Stars n={v.gold_stars} /></dd></div>
                </dl>
                {v.conditions && <div><div className="eyebrow mb-1">Conditions (as submitted)</div><p className="text-sm text-muted">{v.conditions.split("|").slice(0, 12).join(" · ")}</p></div>}
                {pops.length > 0 && (
                  <div>
                    <div className="eyebrow mb-1">Population allele frequency</div>
                    <Plot height={240} data={[{
                      type: "bar", x: pops.map((p) => p.id), y: pops.map((p) => p.af ?? 0),
                      customdata: pops.map((p) => [POP_LABELS[p.id] ?? p.id, p.ac, p.an]) as unknown as number[],
                      hovertemplate: "%{customdata[0]}<br>AF %{y:.3e}<br>AC %{customdata[1]:,} / AN %{customdata[2]:,}<extra></extra>",
                      marker: { color: token(v.provenance === "SYNTHETIC" ? "violet" : "accent") },
                    }]} layout={{ yaxis: { title: { text: "AF" }, tickformat: ".1e" }, margin: { l: 60, r: 10, t: 10, b: 40 }, showlegend: false }} />
                    <p className="text-xs text-faint">Aggregate frequencies in gnomAD reference samples; not an indicator of individual risk.</p>
                  </div>
                )}
                {(v.qc_flags?.length ?? 0) > 0 && <div><div className="eyebrow mb-1">QC flags</div><div className="flex flex-wrap gap-1.5">{v.qc_flags!.map((f) => <span key={f} className="chip border-line font-mono text-muted">{f}</span>)}</div></div>}
                {v.anomalies.length > 0 && (
                  <div><div className="eyebrow mb-2">Screening flags</div>
                    <ul className="space-y-3">{v.anomalies.map((a, i) => (
                      <li key={i} className="space-y-2">
                        <div className="flex flex-wrap items-center gap-2"><PriorityBadge p={a.priority} /><span className="text-[12.5px] text-muted">{a.kind.replace("_", " ")}</span></div>
                        <Insight compact label={a.headline ?? a.category.replace(/_/g, " ")} reason={a.reason ?? a.explanation}>
                          {a.why_it_matters && <p>{a.why_it_matters}</p>}
                          {a.recommendation && <p><b>Recommended next step:</b> {a.recommendation}</p>}
                        </Insight>
                      </li>))}</ul>
                    <details className="mt-3 rounded-xl border border-line bg-raised/40 p-3 text-[13px]">
                      <summary className="cursor-pointer font-semibold text-muted">Technical evidence (raw screening values)</summary>
                      <pre className="mt-2 max-h-64 overflow-auto rounded-lg bg-bg/60 p-3 font-mono text-[11.5px] text-muted scrollbar-thin">{JSON.stringify(v.anomalies.map((a) => ({ category: a.category, score: a.score, evidence: a.evidence })), null, 2)}</pre>
                    </details>
                  </div>
                )}
                {v.provenance === "REAL" && (
                  <div className="rounded-xl border border-line bg-raised/40 p-4">
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <div><div className="eyebrow">External annotation</div><div className="text-[13px] text-muted">Ensembl VEP consequence + NCBI dbSNP RefSNP record, fetched live</div></div>
                      {!ann && <button className="btn-ghost !py-1.5 text-[13px]" disabled={annBusy} onClick={annotate}>{annBusy ? "Fetching…" : "Annotate"}</button>}
                    </div>
                    {annBusy && <div className="mt-3"><HelixLoader label="Querying Ensembl and dbSNP" /></div>}
                    {annErr && <div className="mt-3"><ErrorState message={annErr} /></div>}
                    {ann && (
                      <div className="mt-3 space-y-3 text-[13.5px]">
                        {ann.vep ? (
                          <dl className="grid grid-cols-2 gap-x-4 gap-y-2">
                            <div><dt className="eyebrow">Most severe consequence</dt><dd>{ann.vep.most_severe_consequence?.replace(/_/g, " ")}</dd></div>
                            <div><dt className="eyebrow">Impact</dt><dd>{ann.vep.impact ?? "—"}</dd></div>
                            <div><dt className="eyebrow">Transcript</dt><dd className="data">{ann.vep.transcript ?? "—"}</dd></div>
                            <div><dt className="eyebrow">Amino acids</dt><dd className="data">{ann.vep.amino_acids ? `${ann.vep.amino_acids} @ ${ann.vep.protein_position}` : "—"}</dd></div>
                            <div><dt className="eyebrow">SIFT</dt><dd>{ann.vep.sift ?? "—"}</dd></div>
                            <div><dt className="eyebrow">PolyPhen</dt><dd>{ann.vep.polyphen ?? "—"}</dd></div>
                          </dl>
                        ) : <p className="text-muted">VEP: {ann.vep_error ?? "not available for this record"}</p>}
                        {ann.dbsnp ? (
                          <div>
                            <div className="eyebrow mb-1">dbSNP {ann.dbsnp.rsid} · {ann.dbsnp.build}</div>
                            <div className="max-h-48 overflow-auto rounded-lg border border-line scrollbar-thin">
                              <table className="w-full text-[12.5px]"><thead><tr>{["Study", "Allele", "AC / AN", "AF"].map((h) => <th key={h} className="table-head !py-1.5">{h}</th>)}</tr></thead>
                                <tbody>{ann.dbsnp.frequencies.map((f, i) => <tr key={i}><td className="table-cell !py-1">{f.study}</td><td className="table-cell data !py-1">{f.allele}</td><td className="table-cell data !py-1">{fmtInt(f.allele_count)} / {fmtInt(f.total_count)}</td><td className="table-cell data !py-1">{fmtAF(f.af)}</td></tr>)}</tbody></table>
                            </div>
                            <p className="mt-1 text-[12px] text-faint">Study frequencies are for the listed allele (often the reference allele).</p>
                          </div>
                        ) : v.rsid ? <p className="text-muted">dbSNP: {ann.dbsnp_error ?? "not available"}</p> : <p className="text-muted">No rsID – dbSNP lookup skipped.</p>}
                      </div>
                    )}
                  </div>
                )}
                {v.links && <div className="flex flex-wrap gap-2">
                  {v.links.gnomad && <a className="btn-ghost text-xs" href={v.links.gnomad} target="_blank" rel="noreferrer">gnomAD browser <ExternalLink size={12} /></a>}
                  {v.links.clinvar && <a className="btn-ghost text-xs" href={v.links.clinvar} target="_blank" rel="noreferrer">ClinVar record <ExternalLink size={12} /></a>}
                </div>}
              </div>
            )}
          </motion.aside>
        </>
      )}
    </AnimatePresence>
  );
}

type SortKey = "pos" | "af" | "ac" | "an" | "coarse_class" | "gold_stars" | "match_status";

export default function VariantExplorer() {
  const { analysisId, detail } = useAnalysis();
  const [search, setSearch] = useState("");
  const [q, setQ] = useState("");
  const [classes, setClasses] = useState<CoarseClass[]>([]);
  const [match, setMatch] = useState("");
  const { mode: prov } = useProvenance();
  const [minAf, setMinAf] = useState("");
  const [maxAf, setMaxAf] = useState("");
  const [flagged, setFlagged] = useState(false);
  const [sort, setSort] = useState<SortKey>("pos");
  const [order, setOrder] = useState<"asc" | "desc">("asc");
  const [page, setPage] = useState(1);
  const [pageSize, setPageSize] = useState(50);
  const [open, setOpen] = useState<number | null>(null);

  useEffect(() => { const t = setTimeout(() => setQ(search), 350); return () => clearTimeout(t); }, [search]);
  useEffect(() => setPage(1), [q, classes, match, prov, minAf, maxAf, flagged, pageSize]);

  const params = useMemo(() => ({
    analysis_id: analysisId ?? undefined, provenance: prov, search: q, coarse_class: classes, match_status: match ? [match] : undefined,
    min_af: minAf || undefined, max_af: maxAf || undefined, flagged_only: flagged || undefined,
  }), [analysisId, prov, q, classes, match, minAf, maxAf, flagged]);
  const res = useFetch(analysisId ? () => api.variants({ ...params, page, page_size: pageSize, sort, order }) : null, [params, page, pageSize, sort, order]);

  if (!analysisId) return <NeedsAnalysis />;
  const freq = detail?.results?.dataset?.frequency_source ?? "gnomAD";
  const toggleSort = (k: SortKey) => { if (sort === k) setOrder(order === "asc" ? "desc" : "asc"); else { setSort(k); setOrder(k === "af" ? "desc" : "asc"); } };
  const Th = ({ k, children }: { k?: SortKey; children: string }) => (
    <th className="table-head whitespace-nowrap">
      {k ? <button className="inline-flex items-center gap-1 hover:text-accent" onClick={() => toggleSort(k)} aria-label={`Sort by ${children}`}>{children}
        {sort === k && (order === "asc" ? <ArrowUp size={11} /> : <ArrowDown size={11} />)}</button> : children}
    </th>
  );

  return (
    <motion.div variants={stagger} initial="hidden" animate="show" className="space-y-5">
      <PageHeader index="02" title="Variant Explorer"
        subtitle="Every gnomAD and ClinVar record for the active analysis – matched, unmatched and unmatchable – with server-side search, filtering, sorting and pagination."
        actions={<a className="btn-ghost" href={api.variantExportUrl(params)} download><Download size={15} />Export CSV</a>} />

      <Panel bodyClass="p-4">
        <div className="flex flex-wrap items-center gap-3">
          <div className="relative min-w-[240px] flex-1">
            <Search size={14} className="absolute left-3 top-1/2 -translate-y-1/2 text-faint" />
            <input className="input !pl-9" placeholder="Search key, rsID, HGVS, condition, ClinVar ID…" value={search} onChange={(e) => setSearch(e.target.value)} aria-label="Search variants" />
          </div>
          <span className={`chip px-2.5 py-1 ${prov === "REAL" ? "border-gold/50 text-gold" : prov === "SYNTHETIC" ? "border-pink/50 text-pink" : "border-accent/50 text-accent"}`} title="Change with the Real · Synthetic · Both switch at the top">showing: {prov === "BOTH" ? "real + synthetic" : prov.toLowerCase()}</span>
          <select className="input !w-auto" value={match} onChange={(e) => setMatch(e.target.value)} aria-label="Match status">
            <option value="">All match statuses</option>
            {Object.entries(MATCH_LABELS).map(([k, l]) => <option key={k} value={k}>{l}</option>)}
          </select>
          <input className="input !w-28" placeholder="min AF" value={minAf} onChange={(e) => setMinAf(e.target.value)} aria-label="Minimum allele frequency" />
          <input className="input !w-28" placeholder="max AF" value={maxAf} onChange={(e) => setMaxAf(e.target.value)} aria-label="Maximum allele frequency" />
          <label className="flex items-center gap-2 text-xs text-muted"><input type="checkbox" checked={flagged} onChange={(e) => setFlagged(e.target.checked)} className="accent-[rgb(var(--accent))]" />flagged only</label>
        </div>
        <div className="mt-3 flex flex-wrap gap-2">
          {CLASSES.map((c) => {
            const on = classes.includes(c);
            return (
              <button key={c} onClick={() => setClasses(on ? classes.filter((x) => x !== c) : [...classes, c])} aria-pressed={on}
                className={`chip transition-colors ${on ? `border-${CLASS_META[c].color}/60 bg-${CLASS_META[c].color}/15 text-ink` : "border-line text-muted hover:text-ink"}`}>
                <span className={`h-1.5 w-1.5 rounded-full bg-${CLASS_META[c].color}`} />{CLASS_META[c].short}
              </button>
            );
          })}
          {classes.length > 0 && <button className="text-xs text-faint underline" onClick={() => setClasses([])}>clear</button>}
        </div>
      </Panel>

      <Panel bodyClass="p-0">
        {res.error && <div className="p-4"><ErrorState message={res.error} onRetry={res.reload} /></div>}
        <div className="max-h-[62vh] overflow-auto scrollbar-thin">
          <table className={`w-full min-w-[1100px] ${prov === "BOTH" ? "prov-both" : ""}`}>
            <thead><tr>
              <Th>Variant</Th><Th k="pos">Position</Th><Th>REF › ALT</Th><Th k="af">AF</Th><Th k="ac">AC</Th><Th k="an">AN</Th>
              <Th k="coarse_class">Classification</Th><Th k="gold_stars">Review</Th><Th>Top population</Th><Th k="match_status">Match</Th><Th>Source</Th>
            </tr></thead>
            <tbody className={res.loading ? "opacity-50 transition-opacity" : "transition-opacity"}>
              {res.data?.items.map((v, i) => (
                <motion.tr key={v.id} onClick={() => setOpen(v.id)} onKeyDown={(e) => e.key === "Enter" && setOpen(v.id)} tabIndex={0}
                  initial={{ opacity: 0, y: 4 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.25, delay: Math.min(i, 20) * 0.012 }}
                  className={`cursor-pointer transition-colors hover:bg-raised/70 focus:bg-raised/70 focus:outline-none ${open === v.id ? "bg-accent/[0.06]" : ""} ${prov === "BOTH" ? (v.provenance === "SYNTHETIC" ? "prov-synthetic" : "prov-real") : ""}`}>
                  <td className="table-cell max-w-[240px]"><div className={`truncate font-mono text-[13px] ${v.provenance === "SYNTHETIC" && prov !== "BOTH" ? "syn-id inline-block max-w-full" : ""}`}>{v.variant_key}</div><div className="truncate text-[12px] text-faint">{v.hgvsp ?? v.hgvsc ?? v.name ?? v.rsid ?? ""}</div></td>
                  <td className="table-cell data text-xs">{v.chrom}:{fmtInt(v.pos)}</td>
                  <td className="table-cell max-w-[120px] truncate font-mono text-xs" title={`${v.ref} > ${v.alt}`}>{v.ref || "–"} › {v.alt || "–"}</td>
                  <td className="table-cell data text-xs">{fmtAF(v.af)}</td>
                  <td className="table-cell data text-xs">{fmtInt(v.ac)}</td>
                  <td className="table-cell data text-xs">{fmtInt(v.an)}</td>
                  <td className="table-cell"><ClassBadge cls={v.coarse_class} label={v.clinical_significance} /></td>
                  <td className="table-cell"><Stars n={v.gold_stars} /></td>
                  <td className="table-cell text-xs text-muted">{v.popmax_population ? `${v.popmax_population} · ${fmtAF(v.popmax_af)}` : "—"}</td>
                  <td className="table-cell"><MatchBadge s={v.match_status} /></td>
                  <td className="table-cell"><ProvenanceBadge p={v.provenance} source={v.provenance === "REAL" ? freq : null} /></td>
                </motion.tr>
              ))}
              {res.data && res.data.items.length === 0 && <tr><td colSpan={11} className="p-10 text-center text-sm text-muted">No records match these filters.</td></tr>}
            </tbody>
          </table>
        </div>
        <div className="flex flex-wrap items-center justify-between gap-3 border-t border-line px-4 py-3 text-sm">
          <span className="text-muted">{res.data ? `${fmtInt(res.data.total)} records · page ${res.data.page} of ${Math.max(1, res.data.pages ?? 1)}` : "…"}</span>
          <div className="flex items-center gap-2">
            <select className="input !w-auto !py-1 text-xs" value={pageSize} onChange={(e) => setPageSize(Number(e.target.value))} aria-label="Rows per page">
              {[25, 50, 100, 250].map((n) => <option key={n} value={n}>{n} / page</option>)}
            </select>
            <button className="btn-ghost !px-2 !py-1" disabled={page <= 1} onClick={() => setPage(page - 1)} aria-label="Previous page"><ChevronLeft size={15} /></button>
            <button className="btn-ghost !px-2 !py-1" disabled={!res.data || page >= (res.data.pages ?? 1)} onClick={() => setPage(page + 1)} aria-label="Next page"><ChevronRight size={15} /></button>
          </div>
        </div>
      </Panel>
      <Guide title="How to read this table">
        <GuideItem term={<><Term k="AF">Allele frequency (AF)</Term></>}>How often the alternate allele occurs among sampled chromosomes. It is calculated as <b>AF = AC ÷ AN</b>. A value of <b>1.0e-5</b> means about <b>1 in 100,000</b> chromosomes.</GuideItem>
        <GuideItem term={<><Term k="AC">AC</Term> and <Term k="AN">AN</Term></>}><b>AC</b> (allele count) is how many sampled chromosomes carry the allele; <b>AN</b> (allele number) is how many chromosomes were confidently genotyped. Example: AC = 3, AN = 300,000 → AF = 0.00001.</GuideItem>
        <GuideItem term="Missing values (—)">A dash means the value is <b>not reported</b>. A missing AN or AF is <b>not</b> the same as zero – the site may be uncovered, filtered, or absent from the selected dataset.</GuideItem>
        <GuideItem term="Match status">How a frequency record was linked to ClinVar: <b>Exact</b> (identical chromosome-position-alleles), <b>Normalized</b> (same allele written differently, e.g. indel anchors), <b>Ambiguous</b>, or unmatched (<b>gnomAD/ClinVar only</b>, <b>Unmatchable</b>). Records are never joined by gene name.</GuideItem>
        <GuideItem term={<>Review stars (<Term k="review stars">★</Term>)</>}>How thoroughly a ClinVar classification was reviewed: 0 = no assertion criteria … 4 = practice guideline. More stars = more confidence in the label, not in the biology.</GuideItem>
        <GuideItem term="Real, synthetic and both">Use the <b>Real · Synthetic · Both</b> switch at the top. In <b>Both</b> mode, real records are outlined in <b className="text-gold">gold</b> and synthetic ones in <b className="text-pink">pink</b>. Synthetic records are simulated and are never real observations.</GuideItem>
      </Guide>
      <VariantDrawer id={open} onClose={() => setOpen(null)} />
    </motion.div>
  );
}
