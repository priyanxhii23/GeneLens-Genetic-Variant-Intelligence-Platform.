/**
 * Variant inspection drawer. Shows structured, human-readable information only –
 * no raw JSON or internal screening values. Missing values are stated explicitly.
 */
import { AnimatePresence, motion } from "framer-motion";
import { Compass, ExternalLink, HelpCircle, X } from "lucide-react";
import { useEffect, useState, type ReactNode } from "react";
import { api } from "../lib/api";
import { fmtAF, fmtInt, POP_LABELS, token } from "../lib/format";
import type { Annotation, VariantDetail } from "../lib/types";
import Plot from "./Plot";
import { ClassBadge, ErrorState, HelixLoader, MatchBadge, PriorityBadge, ProvenanceBadge, Stars } from "./ui";

const NA = "Not available in source record.";
const METHOD_TEXT: Record<string, string> = {
  vcf_key_exact: "Identical chromosome, position and alleles in both sources",
  minimal_representation: "Same allele after normalising how insertions/deletions are written",
  "vcf_key_exact+discordant_clinvar_records": "Exact allele match, but ClinVar holds records with different classifications",
  "minimal_representation+discordant_clinvar_records": "Normalised allele match, but ClinVar holds records with different classifications",
  no_clinvar_record: "No ClinVar record for this allele",
  no_gnomad_record_at_allele: "This allele is not present in the frequency dataset",
  no_allele_level_coordinates: "The ClinVar record has no allele-level coordinates, so it cannot be matched",
  minimal_key_multiple_gnomad_hits: "The allele maps to several frequency records",
  generated: "Generated by the synthetic data lab",
  custom_upload: "Uploaded by the researcher (custom dataset)",
};

function Field({ label, value, mono = false }: { label: string; value: ReactNode; mono?: boolean }) {
  const empty = value === null || value === undefined || value === "" || value === "—";
  return (
    <div className="min-w-0">
      <dt className="eyebrow">{label}</dt>
      <dd className={`mt-0.5 break-words ${empty ? "text-[13px] italic text-faint" : mono ? "data text-[14px]" : "text-[14.5px]"}`}>{empty ? NA : value}</dd>
    </div>
  );
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section>
      <h4 className="mb-2 font-display text-[18px]">{title}</h4>
      <dl className="grid grid-cols-2 gap-x-5 gap-y-3">{children}</dl>
    </section>
  );
}

export default function VariantDrawer({ id, onClose }: { id: number | null; onClose: () => void }) {
  const [v, setV] = useState<VariantDetail | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [ann, setAnn] = useState<Annotation | null>(null);
  const [annBusy, setAnnBusy] = useState(false);
  const [annErr, setAnnErr] = useState<string | null>(null);
  useEffect(() => {
    setV(null); setErr(null); setAnn(null); setAnnErr(null);
    if (id !== null) api.variant(id).then(setV).catch((e) => setErr(e.message));
  }, [id]);
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);
  const annotate = () => {
    if (id === null) return;
    setAnnBusy(true); setAnnErr(null);
    api.annotation(id).then(setAnn).catch((e) => setAnnErr(e.message)).finally(() => setAnnBusy(false));
  };
  const pops = (v?.populations ?? []).filter((p) => p.an > 0);
  const num = (x: number | null | undefined) => (x === null || x === undefined ? null : fmtInt(x));
  const af = (x: number | null | undefined) => (x === null || x === undefined ? null : fmtAF(x));

  return (
    <AnimatePresence>
      {id !== null && (
        <>
          <motion.div className="fixed inset-0 z-40 bg-bg/60 backdrop-blur-sm" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={onClose} />
          <motion.aside role="dialog" aria-label="Variant inspection" initial={{ x: "100%" }} animate={{ x: 0 }} exit={{ x: "100%" }} transition={{ type: "spring", damping: 30, stiffness: 260 }}
            className="fixed inset-y-0 right-0 z-50 w-full max-w-xl overflow-y-auto border-l border-line bg-surface p-6 scrollbar-thin">
            <button className="btn-ghost absolute right-4 top-4 !px-2" onClick={onClose} aria-label="Close"><X size={16} /></button>
            {err && <ErrorState message={err} />}
            {!v && !err && <HelixLoader label="Loading variant" />}
            {v && (
              <div className="space-y-6">
                <div>
                  <div className="eyebrow mb-1">variant inspection</div>
                  <h2 className={`break-all font-mono text-[17px] ${v.provenance === "SYNTHETIC" ? "syn-id inline-block" : ""}`}>{v.variant_key}</h2>
                  <div className="mt-2 flex flex-wrap gap-2">
                    <ProvenanceBadge p={v.provenance} />
                    <ClassBadge cls={v.coarse_class} label={v.clinical_significance} />
                    <MatchBadge s={v.match_status} />
                  </div>
                  {v.provenance === "SYNTHETIC" && <p className="mt-2 text-[13px] text-pink">Simulated record generated by GeneLens – not an observation from any database.</p>}
                  {v.provenance === "CUSTOM" && <p className="mt-2 text-[13px] text-violet">Uploaded by the researcher (CUSTOM DATA) – not an official gnomAD or ClinVar record.</p>}
                </div>

                {v.anomalies.length > 0 && (
                  <section className="space-y-4">
                    {v.anomalies.map((a, i) => (
                      <div key={i} className="rounded-2xl border border-line bg-raised/40 p-4">
                        <div className="mb-2 flex flex-wrap items-center gap-2"><PriorityBadge p={a.priority} /><span className="text-[12.5px] text-muted">{a.kind.replace("_", " ")} · {a.headline}</span></div>
                        <div className="mb-1 flex items-center gap-1.5 text-[14px] font-bold"><HelpCircle size={14} className="text-accent" />Why was this variant flagged?</div>
                        <p className="insight-reason !text-[17px]">{a.reason ?? a.explanation}</p>
                        {a.why_it_matters && <><div className="mb-1 mt-3 text-[14px] font-bold">What this means</div><p className="insight-detail">{a.why_it_matters}</p></>}
                        {a.recommendation && <><div className="mb-1 mt-3 flex items-center gap-1.5 text-[14px] font-bold"><Compass size={14} className="text-accent" />Recommended next step</div><p className="insight-detail">{a.recommendation}</p></>}
                      </div>
                    ))}
                  </section>
                )}

                <Section title="Identity">
                  <Field label="Variant identifier" value={v.variant_key} mono />
                  <Field label="Genome assembly" value={v.assembly} />
                  <Field label="Chromosome" value={v.chrom} mono />
                  <Field label="Position" value={num(v.pos)} mono />
                  <Field label="Reference allele" value={v.ref} mono />
                  <Field label="Alternate allele" value={v.alt} mono />
                  <Field label="Variant type" value={v.variant_type && v.variant_type !== "unknown" ? v.variant_type : null} />
                  <Field label="rsID" value={v.rsid} mono />
                  <Field label="HGVS (cDNA)" value={v.hgvsc} mono />
                  <Field label="HGVS (protein)" value={v.hgvsp} mono />
                  <Field label="Consequence" value={v.consequence?.replace(/_/g, " ")} />
                  <Field label="ClinVar name" value={v.name} />
                </Section>

                <Section title="Population frequency">
                  <Field label="Allele frequency (AF)" value={af(v.af)} mono />
                  <Field label="Allele count (AC)" value={num(v.ac)} mono />
                  <Field label="Allele number (AN)" value={num(v.an)} mono />
                  <Field label="Highest group AF (grpmax)" value={v.popmax_af !== null && v.popmax_af !== undefined ? `${fmtAF(v.popmax_af)} (${v.popmax_population})` : null} mono />
                  <Field label="AF exomes" value={af(v.af_exome)} mono />
                  <Field label="AF genomes" value={af(v.af_genome)} mono />
                  <Field label="Homozygotes" value={num(v.homozygote_count)} mono />
                </Section>
                {pops.length > 0 && (
                  <div>
                    <div className="eyebrow mb-1">Population allele frequency</div>
                    <Plot height={230} data={[{
                      type: "bar", x: pops.map((p) => p.id), y: pops.map((p) => p.af ?? 0),
                      customdata: pops.map((p) => [POP_LABELS[p.id] ?? p.id, p.ac, p.an]) as unknown as number[],
                      hovertemplate: "%{customdata[0]}<br>AF %{y:.3e}<br>AC %{customdata[1]:,} / AN %{customdata[2]:,}<extra></extra>",
                      marker: { color: token(v.provenance === "SYNTHETIC" ? "pink" : "accent") },
                    }]} layout={{ yaxis: { title: { text: "AF" }, tickformat: ".1e" }, margin: { l: 60, r: 10, t: 10, b: 40 }, showlegend: false }} />
                    <p className="text-[12.5px] text-faint">Aggregate frequencies in reference samples; not an indicator of individual risk.</p>
                  </div>
                )}

                <Section title="Clinical classification">
                  <Field label="Clinical significance" value={v.clinical_significance} />
                  <Field label="Review status" value={v.review_status} />
                  <Field label="Review stars" value={v.gold_stars !== null && v.gold_stars !== undefined ? <Stars n={v.gold_stars} /> : null} />
                  <Field label="ClinVar variation ID" value={v.clinvar_variation_id} mono />
                  <Field label="ClinVar allele ID" value={v.clinvar_allele_id} mono />
                  <Field label="Submissions" value={num(v.submitter_count)} mono />
                  <Field label="Last evaluated" value={v.last_evaluated} />
                </Section>
                {v.conditions && <div><div className="eyebrow mb-1">Conditions (as submitted)</div><p className="text-[14px] text-muted">{[...new Set(v.conditions.split("|"))].slice(0, 12).join(" · ")}</p></div>}

                <Section title="Matching & provenance">
                  <Field label="Match status" value={<MatchBadge s={v.match_status} />} />
                  <Field label="Match confidence" value={v.match_confidence !== null && v.match_confidence !== undefined ? `${Math.round(v.match_confidence * 100)}%` : null} />
                  <div className="col-span-2"><Field label="How it was matched" value={METHOD_TEXT[v.match_method ?? ""] ?? v.match_method?.replace(/_/g, " ")} /></div>
                  <div className="col-span-2"><Field label="Data provenance" value={v.provenance === "SYNTHETIC" ? "Synthetic record (GeneLens generator)" : v.provenance === "CUSTOM" ? "Researcher-uploaded custom dataset" : `${v.in_gnomad ? `${v.frequency_source ?? "Frequency dataset"} record` : "No frequency record"}${v.in_clinvar ? " + ClinVar record" : ""} (public databases)`} /></div>
                </Section>

                {v.provenance === "REAL" && (
                  <div className="rounded-2xl border border-line bg-raised/40 p-4">
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <div><div className="eyebrow">External annotation</div><div className="text-[13px] text-muted">Ensembl VEP consequence + NCBI dbSNP RefSNP record, fetched live</div></div>
                      {!ann && <button className="btn-ghost !py-1.5 text-[13px]" disabled={annBusy} onClick={annotate}>{annBusy ? "Fetching…" : "Annotate"}</button>}
                    </div>
                    {annBusy && <div className="mt-3"><HelixLoader label="Querying Ensembl and dbSNP" /></div>}
                    {annErr && <div className="mt-3"><ErrorState message={annErr} /></div>}
                    {ann && (
                      <div className="mt-3 space-y-3 text-[13.5px]">
                        {ann.vep ? (
                          <dl className="grid grid-cols-2 gap-x-4 gap-y-2">
                            <Field label="Most severe consequence" value={ann.vep.most_severe_consequence?.replace(/_/g, " ")} />
                            <Field label="Impact" value={ann.vep.impact} />
                            <Field label="Transcript" value={ann.vep.transcript} mono />
                            <Field label="Amino-acid change" value={ann.vep.amino_acids ? `${ann.vep.amino_acids} at ${ann.vep.protein_position}` : null} mono />
                            <Field label="SIFT" value={ann.vep.sift?.replace(/_/g, " ")} />
                            <Field label="PolyPhen" value={ann.vep.polyphen?.replace(/_/g, " ")} />
                          </dl>
                        ) : <p className="text-muted">Ensembl VEP: {ann.vep_error ?? "no annotation returned for this record."}</p>}
                        {ann.dbsnp ? (
                          <div>
                            <div className="eyebrow mb-1">dbSNP {ann.dbsnp.rsid} · {ann.dbsnp.build}</div>
                            <div className="max-h-48 overflow-auto rounded-lg border border-line scrollbar-thin">
                              <table className="w-full text-[12.5px]"><thead><tr>{["Study", "Allele", "AC / AN", "AF"].map((h) => <th key={h} className="table-head !py-1.5">{h}</th>)}</tr></thead>
                                <tbody>{ann.dbsnp.frequencies.map((f, i) => <tr key={i}><td className="table-cell !py-1">{f.study}</td><td className="table-cell data !py-1">{f.allele}</td><td className="table-cell data !py-1">{fmtInt(f.allele_count)} / {fmtInt(f.total_count)}</td><td className="table-cell data !py-1">{fmtAF(f.af)}</td></tr>)}</tbody></table>
                            </div>
                            <p className="mt-1 text-[12px] text-faint">Study frequencies are for the listed allele (often the reference allele). Retrieved annotation – not part of the original record.</p>
                          </div>
                        ) : v.rsid ? <p className="text-muted">dbSNP: {ann.dbsnp_error ?? "not available."}</p> : <p className="text-muted">No rsID in the source record – dbSNP lookup skipped.</p>}
                      </div>
                    )}
                  </div>
                )}
                {v.links && <div className="flex flex-wrap gap-2">
                  {v.links.gnomad && <a className="btn-ghost text-xs" href={v.links.gnomad} target="_blank" rel="noreferrer">gnomAD browser <ExternalLink size={12} /></a>}
                  {v.links.clinvar && <a className="btn-ghost text-xs" href={v.links.clinvar} target="_blank" rel="noreferrer">ClinVar record <ExternalLink size={12} /></a>}
                </div>}
              </div>
            )}
          </motion.aside>
        </>
      )}
    </AnimatePresence>
  );
}
